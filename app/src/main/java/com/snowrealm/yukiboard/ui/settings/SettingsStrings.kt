package com.snowrealm.yukiboard.ui.settings

/**
 * 設定頁面多語言翻譯 — 支援中/英/日/韓。
 *
 * 使用方式：SettingsStrings.tr("中文原文", lang)
 * 預設 lang="zh" 時直接回傳原文，不查表。
 */
object SettingsStrings {

    enum class Lang(val code: String, val displayName: String) {
        ZH("zh", "中文"),
        EN("en", "English"),
        JA("ja", "日本語"),
        KO("ko", "한국어"),
        DE("de", "Deutsch"),
        FR("fr", "Français"),
        ES("es", "Español"),
        VI("vi", "Tiếng Việt"),
        IT("it", "Italiano");

        companion object {
            fun fromCode(code: String): Lang = entries.find { it.code == code } ?: EN
        }
    }

    /** 翻譯：傳入中文原文 + 語言，回傳對應翻譯 */
    fun tr(zh: String, lang: Lang): String {
        if (lang == Lang.ZH) return zh
        val table = when (lang) {
            Lang.EN -> en
            Lang.JA -> ja
            Lang.KO -> ko
            Lang.DE -> de
            Lang.FR -> fr
            Lang.ES -> es
            Lang.VI -> vi
            Lang.IT -> it
            Lang.ZH -> return zh
        }
        return table[zh] ?: en[zh] ?: zh  // fallback: 英文 → 中文原文
    }

